#!/usr/bin/env bash
# ⛔ АМЕРИКАНСКОЕ НАПИСАНИЕ НА ВИТРИНЕ — ТЕМ ЖЕ ЗАМКОМ, ЧТО В ПРИЛОЖЕНИИ.
# Витрину читают только семьи: смотрим всё, что отдаётся браузеру.
# ⚠️ КАТАЛОГ БЕРЁТСЯ ОТ СКРИПТА, А НЕ ОТ ТОГО, ОТКУДА ЕГО ПОЗВАЛИ: первая проба
# запустилась из каталога приложения и «нашла» британское написание в чужом
# собранном бандле. Проверка, зависящая от места вызова, врёт по-разному каждый раз.
set -u
cd "$(dirname "$0")" || exit 1
HITS=$(grep -rn --include=*.html --include=*.js --include=*.json --include=*.css -i "centre" . 2>/dev/null | grep -v "^\./\.git/")
if [ -n "$HITS" ]; then
  echo "⛔ британское «centre» вернулось на витрину:"; echo "$HITS" | head -40
  echo; echo "Американское написание — стандарт продукта (слово владельца 27.08)."; exit 1
fi
echo "написание американское: «centre» на витрине не найдено"
